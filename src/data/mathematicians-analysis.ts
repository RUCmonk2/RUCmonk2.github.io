const l = (zh: string, en: string) => ({ zh, en });
const mt = (name: string) =>
  `https://mathshistory.st-andrews.ac.uk/Biographies/${name}/`;
const hardyZeros =
  "https://fr.wikisource.org/wiki/Page:Comptes_rendus_hebdomadaires_des_s%C3%A9ances_de_l%E2%80%99Acad%C3%A9mie_des_sciences,_tome_158,_1914.djvu/1014";
const source = (title: string, href: string) => ({ title, href });
const life = (year: string, zh: string, en: string) => ({
  year,
  text: l(zh, en),
});
const work = (
  year: string,
  zh: string,
  en: string,
  descriptionZh: string,
  descriptionEn: string,
  formula?: string,
) => ({
  year,
  title: l(zh, en),
  description: l(descriptionZh, descriptionEn),
  ...(formula ? { formula } : {}),
});
function portrait(
  id: string,
  file: string,
  altZh: string,
  altEn: string,
  creditZh: string,
  creditEn: string,
  kind: "portrait" | "later-depiction" = "portrait",
): Mathematician["portrait"] {
  return {
    src: `/images/mathematicians/analysis/${id}.${id === "poincare" ? "png" : "jpg"}`,
    kind,
    alt: l(altZh, altEn),
    credit: l(creditZh, creditEn),
    href: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(file)}`,
    ...(id === "ramanujan"
      ? {
          license: {
            label: "CC BY 4.0",
            href: "https://creativecommons.org/licenses/by/4.0/",
          },
        }
      : {}),
  };
}

