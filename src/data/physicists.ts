function P(
  id: string,
  zh: string,
  en: string,
  born: number,
  died: number | null,
  placeZh: string,
  placeEn: string,
  fieldZh: string,
  fieldEn: string,
  hookZh: string,
  hookEn: string,
  summaryZh: string,
  summaryEn: string,
  achievements: Mathematician["achievements"],
  milestones: Mathematician["timeline"],
  sources: Mathematician["sources"],
  lifeDates?: Mathematician["lifeDates"],
): Mathematician {
  return {
    id,
    name: l(zh, en),
    fullName: en,
    born,
    died,
    place: l(placeZh, placeEn),
    field: l(fieldZh, fieldEn),
    hook: l(hookZh, hookEn),
    summary: l(summaryZh, summaryEn),
    ...(lifeDates
      ? { lifeDates }
      : died === null
        ? { lifeDates: l(`${born}年生`, `Born ${born}`) }
        : {}),
    portrait: portraitRecords[id] ?? {
      src: `/images/physicists/${id}.svg`,
      kind: "monogram",
      alt: l(`${zh}的姓名字标，非肖像`, `Name mark for ${en}, not a likeness`),
      credit: l(
        "未采用已核实开放许可的肖像，使用本站原创姓名字标",
        "Original name mark; no verified openly licensed portrait used",
      ),
      href: sources[0].href,
      license: {
        label: "CC0",
        href: "https://creativecommons.org/publicdomain/zero/1.0/",
      },
    },
    achievements,
    timeline: [
      event(String(born), "出生。", "Born."),
      ...milestones,
      event(
        died === null ? "2025" : String(died),
        died === null ? "持续参与科学交流与公共教育。" : "去世。",
        died === null
          ? "Continued scientific engagement and public education."
          : "Died.",
      ),
    ],
    sources,
  };
}

