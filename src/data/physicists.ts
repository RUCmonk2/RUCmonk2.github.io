import type { Mathematician, ScholarRelation } from "./mathematicians";

const l = (zh: string, en: string) => ({ zh, en });
const source = (title: string, href: string) => ({ title, href });
const mt = (name: string) =>
  `https://mathshistory.st-andrews.ac.uk/Biographies/${name}/`;
const history = (name: string, title: string, href: string) => [
  source(`MacTutor · ${name.replaceAll("_", " ")}`, mt(name)),
  source(title, href),
];
const nobel = (year: number, name: string, category = "physics") => [
  source(
    "Nobel Prize · Biographical record",
    `https://www.nobelprize.org/prizes/${category}/${year}/${name}/biographical/`,
  ),
  source(
    "Nobel Prize · Original Nobel lecture",
    `https://www.nobelprize.org/prizes/${category}/${year}/${name}/lecture/`,
  ),
];
const work = (
  year: string,
  zh: string,
  en: string,
  dz: string,
  de: string,
  formula?: string,
): Mathematician["achievements"][number] => ({
  year,
  title: l(zh, en),
  description: l(dz, de),
  ...(formula ? { formula } : {}),
});
const event = (year: string, zh: string, en: string) => ({
  year,
  text: l(zh, en),
});

