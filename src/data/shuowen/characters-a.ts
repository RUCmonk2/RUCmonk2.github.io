const dictionary = (char: string) => `https://humanum.arts.cuhk.edu.hk/Lexis/lexi-mf/search.php?word=${encodeURIComponent(char)}`;
const laozi = "https://zh.wikisource.org/wiki/道德經_(王弼本)";
type Draft = {
  id: string; char: string; traditional?: string; pinyin: string; theme: ShuowenTheme;
  subtitle: string; radical: string; headword?: string; sourceCharacter?: string; status?: "recorded" | "related";
  original: string; explanation: string; formation: string; chapter: string; quote: string;
  reading: string; reflection: string; caution: string; aliases?: string[];
  components?: CharacterEntry["components"]; extraSources?: CharacterEntry["sources"];
};
function entry(d: Draft): CharacterEntry {
  const traditional = d.traditional ?? d.char;
  const sourceCharacter = d.sourceCharacter ?? d.headword ?? traditional;
  const sourceUrl = dictionary(sourceCharacter);
  return {
    id: d.id, char: d.char, traditional, pinyin: d.pinyin, theme: d.theme,
    subtitle: d.subtitle, radical: d.radical, aliases: d.aliases ?? (traditional === d.char ? [] : [traditional]),
    shuowen: { headword: d.headword ?? traditional, status: d.status ?? "recorded", original: d.original, explanation: d.explanation, sourceUrl },
    formation: d.formation, components: d.components ?? [],
    passages: [{ work: "道德经", chapter: d.chapter, quote: d.quote, explanation: d.reading, sourceUrl: `${laozi}#${d.chapter.replace(/^第/, "")}` }],
    reflection: d.reflection, caution: d.caution,
    sources: [{ label: `汉语多功能字库 · ${sourceCharacter}`, url: sourceUrl }, { label: "《道德经》王弼本正文与注", url: laozi }, ...(d.extraSources ?? [])],
  };
}

