const dictionary = (char: string) =>
  `https://humanum.arts.cuhk.edu.hk/Lexis/lexi-mf/search.php?word=${encodeURIComponent(char)}`;
const daoUrl = "https://zh.wikisource.org/wiki/道德經_(王弼本)";
const sw = (
  headword: string,
  original: string,
  explanation: string,
  status: "recorded" | "related" = "recorded",
  lookup = headword,
): CharacterEntry["shuowen"] => ({
  headword,
  original,
  explanation,
  status,
  sourceUrl: dictionary(lookup),
});
const dao = (
  chapter: string,
  quote: string,
  explanation: string,
): CharacterEntry["passages"][number] => ({
  work: "《老子》",
  chapter: `第${chapter}章`,
  quote,
  explanation,
  sourceUrl: `${daoUrl}#${chapter}章`,
});
const zhuang = (
  chapter: string,
  quote: string,
  explanation: string,
): CharacterEntry["passages"][number] => ({
  work: "《庄子》",
  chapter,
  quote,
  explanation,
  sourceUrl: `https://zh.wikisource.org/wiki/莊子/${chapter}`,
});
const entry = (
  value: Omit<CharacterEntry, "sources">,
  extraSources: CharacterEntry["sources"] = [],
): CharacterEntry => ({
  ...value,
  sources: [
    { label: "香港中文大学 · 字形与《说文》", url: value.shuowen.sourceUrl },
    ...value.passages.map((p) => ({
      label: `${p.work}·${p.chapter}原文`,
      url: p.sourceUrl,
    })),
    ...extraSources,
  ],
});

