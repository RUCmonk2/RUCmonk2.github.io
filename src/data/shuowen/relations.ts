function locateSource(sourceUrl: string | undefined, explanation: string): string | undefined {
  if (sourceUrl === laozi) {
    const chapter = explanation.match(/《老子》第([一二三四五六七八九十百]+)章/);
    if (!chapter) throw new Error(`老子关系缺少可定位的章号：${explanation}`);
    return `${laozi}#${chapter[1]}章`;
  }
  if (sourceUrl === zhuangzi) {
    const chapter = explanation.match(/《庄子·([^》]+)》/)?.[1];
    const title = chapter && zhuangziChapters[chapter];
    if (!title) throw new Error(`庄子关系缺少可定位的篇名：${explanation}`);
    return `${zhuangzi}/${title}`;
  }
  return sourceUrl;
}

